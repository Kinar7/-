namespace Content.Client._Sunrise.Latejoin;

[GenerateTypedNameReferences]
public sealed partial class SRLateJoinGui : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;
    [Dependency] private readonly IConsoleHost _consoleHost = default!;
    [Dependency] private readonly JobRequirementsManager _playManager = default!;
    [Dependency] private readonly IClientPreferencesManager _preferencesManager = default!;

    private ClientGameTicker _gameTicker;

    private NetEntity _lastSelection;

    private readonly Dictionary<string, BoxContainer> _jobCategories;
    private readonly Dictionary<string, SRLateJoinJobButton> _buttons = new();

    // Dropdown state: stores the dropdown container per job and tracks which one is open.
    private readonly Dictionary<string, BoxContainer> _dropdowns = new();
    private string? _expandedJobId;

    public SRLateJoinGui()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _gameTicker = EntitySystem.Get<ClientGameTicker>();
        _gameTicker.LobbyJobsAvailableUpdated += UpdateUi;

        _jobCategories = new Dictionary<string, BoxContainer>();
        StationSelection.StationsItemList.OnItemSelected += args =>
        {
            UpdateUi(_gameTicker.JobsAvailable);
        };
        CrewManifestButton.OnPressed += _ =>
        {
            EntitySystem.Get<CrewManifestSystem>().RequestCrewManifest(_lastSelection);
        };

        _lastSelection = _gameTicker.JobsAvailable.Keys.FirstOrNull() ?? NetEntity.Invalid;

        UpdateUi(_gameTicker.JobsAvailable);
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        _gameTicker.LobbyJobsAvailableUpdated -= UpdateUi;
    }

    public void UpdateUi(IReadOnlyDictionary<NetEntity, Dictionary<ProtoId<JobPrototype>, int?>> obj)
    {
        if (StationSelection.Selected is null)
        {
            CrewManifestButton.Visible = false;
            return;
        }

        CrewManifestButton.Visible = true;

        var station = StationSelection.Selected.Value;
        var jobs = obj[station];

        if (station != _lastSelection)
        {
            foreach (var (_, button) in _buttons)
            {
                JobList.RemoveChild(button);
            }
            _buttons.Clear();

            foreach (var (_, dropdown) in _dropdowns)
            {
                JobList.RemoveChild(dropdown);
            }
            _dropdowns.Clear();
            _expandedJobId = null;

            foreach (var (_, box) in _jobCategories)
            {
                JobList.RemoveChild(box);
            }
            _jobCategories.Clear();
        }

        _lastSelection = station;

        var departments = new List<DepartmentPrototype>();
        foreach (var department in _prototypeManager.EnumeratePrototypes<DepartmentPrototype>())
        {
            if (department.EditorHidden)
                continue;

            departments.Add(department);
        }

        departments.Sort(DepartmentUIComparer.Instance);

        foreach (var department in departments)
        {
            var departmentName = Loc.GetString($"department-{department.ID}");

            var hasRole = false;
            foreach (var (jobId, _) in jobs)
            {
                if (department.Roles.Contains(jobId))
                {
                    hasRole = true;
                    break;
                }
            }

            if (!hasRole)
            {
                continue;
            }

            if (!_jobCategories.TryGetValue(department.ID, out var category))
            {
                category = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    Name = department.ID,
                    ToolTip = Loc.GetString("humanoid-profile-editor-jobs-amount-in-department-tooltip",
                        ("departmentName", departmentName))
                };

                var departamentLabel = new Label
                {
                    Text = Loc.GetString("humanoid-profile-editor-department-jobs-label",
                        ("departmentName", departmentName)),
                    Margin = new Thickness(5f, 0, 0, 0)
                };

                category.AddChild(new StripeBack()
                {
                    Visible = true,
                    HorizontalExpand = true,
                    HasMargins = true,
                    MouseFilter = MouseFilterMode.Stop,
                    Children =
                    {
                        departamentLabel
                    }
                });

                _jobCategories[department.ID] = category;
                JobList.AddChild(category);
            }

            foreach (var (jobId, _) in jobs)
            {
                if (!department.Roles.Contains(jobId))
                    continue;

                if (_buttons.ContainsKey(jobId))
                    continue;

                var job = _prototypeManager.Index(jobId);

                var newButton = new SRLateJoinJobButton(station, jobId, _gameTicker, _prototypeManager);

                var isAllowed = true;
                if (!_playManager.IsAllowed(
                    job,
                    (HumanoidCharacterProfile?)_preferencesManager.Preferences?.SelectedCharacter,
                    out var denyReason))
                {
                    isAllowed = false;
                    newButton.Disabled = true;
                    newButton.ToolTip = denyReason.ToString();
                }

                if (job.AlternativeNames.Count == 0)
                {
                    // No alternatives: click directly joins.
                    newButton.OnPressed += _ =>
                    {
                        Logger.InfoS("latejoin", $"Late joining as ID: {jobId}");
                        _consoleHost.ExecuteCommand($"joingame {CommandParsing.Escape(jobId)} {station}");
                        Close();
                    };

                    category.AddChild(newButton);
                }
                else
                {
                    // Has alternatives: click toggles a dropdown with name choices.
                    newButton.OnPressed += _ => ToggleDropdown(jobId);

                    // Build the dropdown panel (hidden by default).
                    var dropdown = BuildNameDropdown(job, jobId, station);
                    if (!isAllowed)
                    {
                        // Disable all name choice buttons if the job itself is locked.
                        foreach (var child in dropdown.Children)
                        {
                            if (child is Button btn)
                                btn.Disabled = true;
                        }
                    }

                    category.AddChild(newButton);
                    category.AddChild(dropdown);

                    _dropdowns[jobId] = dropdown;
                }

                _buttons.Add(jobId, newButton);
            }
        }
    }

    /// <summary>
    /// Builds a dropdown container with buttons for the job's main name and all alternative names.
    /// </summary>
    private BoxContainer BuildNameDropdown(JobPrototype job, string jobId, NetEntity station)
    {
        var dropdown = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Visible = false,
            Margin = new Thickness(16, 0, 0, 0),
        };

        // Main name button.
        var spriteSystem = EntitySystem.Get<SpriteSystem>();
        dropdown.AddChild(CreateNameChoiceButton(job.Icon, job.LocalizedName, jobId, station, null, spriteSystem));

        // Alternative name buttons.
        foreach (var alt in job.AlternativeNames)
        {
            var iconId = alt.Icon ?? job.Icon;
            dropdown.AddChild(CreateNameChoiceButton(iconId, alt.LocalizedName, jobId, station, alt.Name, spriteSystem));
        }

        return dropdown;
    }

    /// <summary>
    /// Creates a single name-choice button inside a dropdown.
    /// </summary>
    private Button CreateNameChoiceButton(
        ProtoId<JobIconPrototype> iconId,
        string displayName,
        string jobId,
        NetEntity station,
        string? altKey,
        SpriteSystem spriteSystem)
    {
        var btn = new Button
        {
            HorizontalExpand = true,
        };

        var container = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
        };

        var icon = new TextureRect
        {
            TextureScale = new Vector2(2, 2),
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(0, 0, 4, 0),
        };

        if (_prototypeManager.TryIndex(iconId, out JobIconPrototype? jobIconProto))
            icon.Texture = spriteSystem.Frame0(jobIconProto.Icon);

        var label = new Label
        {
            Text = displayName,
            Margin = new Thickness(2, 0),
        };

        container.AddChild(icon);
        container.AddChild(label);
        btn.AddChild(container);

        btn.OnPressed += _ =>
        {
            var cmd = altKey != null
                ? $"joingame {CommandParsing.Escape(jobId)} {station} {CommandParsing.Escape(altKey)}"
                : $"joingame {CommandParsing.Escape(jobId)} {station}";
            Logger.InfoS("latejoin", $"Late joining as ID: {jobId} display: {displayName}");
            _consoleHost.ExecuteCommand(cmd);
            Close();
        };

        return btn;
    }

    /// <summary>
    /// Toggles the dropdown for the given job. Closes any previously open dropdown.
    /// </summary>
    private void ToggleDropdown(string jobId)
    {
        if (_expandedJobId == jobId)
        {
            // Collapse current dropdown.
            if (_dropdowns.TryGetValue(jobId, out var dd))
                dd.Visible = false;
            _expandedJobId = null;
        }
        else
        {
            // Collapse previous dropdown.
            if (_expandedJobId != null && _dropdowns.TryGetValue(_expandedJobId, out var prevDd))
                prevDd.Visible = false;

            // Expand new dropdown.
            if (_dropdowns.TryGetValue(jobId, out var newDd))
                newDd.Visible = true;

            _expandedJobId = jobId;
        }
    }
}
